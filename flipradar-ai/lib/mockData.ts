// Computed helpers
export function netProfit(deal: { buyPrice: number; estResalePrice: number; fees: number; shipping: number }): number {
  return deal.estResalePrice - deal.buyPrice - deal.fees - deal.shipping;
}

export function roi(deal: { buyPrice: number; estResalePrice: number; fees: number; shipping: number }): number {
  const profit = netProfit(deal);
  return (profit / deal.buyPrice) * 100;
}

export function ledgerProfit(item: LedgerItem): number | null {
  if (item.salePrice === null) return null;
  return item.salePrice - item.buyPrice - item.fees - item.shipping;
}

export function turnaroundDays(item: LedgerItem): number | null {
  if (!item.soldAt) return null;
  const diff = new Date(item.soldAt).getTime() - new Date(item.acquiredAt).getTime();
  return Math.round(diff / (1000 * 60 * 60 * 24));
}
